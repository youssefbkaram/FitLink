CREATE TABLE IF NOT EXISTS users (
  username TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  age TEXT NOT NULL,
  role TEXT NOT NULL,
  sports JSONB NOT NULL DEFAULT '[]'::jsonb,
  country TEXT,
  points INTEGER NOT NULL DEFAULT 0 CHECK (points >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS academies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_username TEXT REFERENCES users(username) ON DELETE SET NULL,
  data JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS academies_coach_username_idx
  ON academies (coach_username);

CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,
  academy_id BIGINT REFERENCES academies(id) ON DELETE SET NULL,
  subscribe_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS subscriptions_username_idx
  ON subscriptions (username);

CREATE TABLE IF NOT EXISTS user_challenges (
  username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,
  challenge_id INTEGER NOT NULL,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (username, challenge_id)
);

CREATE TABLE IF NOT EXISTS weekly_rewards (
  username TEXT PRIMARY KEY REFERENCES users(username) ON DELETE CASCADE,
  claimed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
